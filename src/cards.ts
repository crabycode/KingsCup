export const DECK: PlayingCard[] = suits.flatMap((suit) =>
  ranks.map((rank) => ({
    id: `${rank}${suit}`,
    rank,
    suit,
    color: suit === '♥' || suit === '♦' ? 'red' : 'black',
    ...rules[rank],
  })),
);

export function getRule(card: PlayingCard, mode: Mode): string {
  return mode === 'party' ? card.partyRule : card.rule;
}

export function shuffleDeck<T>(items: readonly T[], random = Math.random): T[] {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
